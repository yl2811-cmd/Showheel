'use strict';
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.argv[2] || 'http://127.0.0.1:5296';
const output = path.resolve(process.argv[3] || 'web-browser-qa/character-atlas');
fs.mkdirSync(output, { recursive: true });
const result = { checks: [], errors: [], failedResources: [] };
(async () => {
    const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
    try {
        const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, reducedMotion: 'reduce' });
        const page = await context.newPage();
        page.on('pageerror', error => result.errors.push(error.message));
        page.on('response', r => { if (r.url().startsWith(base) && r.status() >= 400) result.failedResources.push({ url: r.url(), status: r.status() }); });
        let contentRequests = 0;
        page.on('request', r => { if (new URL(r.url()).pathname === '/Character') contentRequests++; });
        await page.goto(base + '/Archeon');
        const outer = page.locator('iframe[src="/archeon-atlas/index.html"]');
        await outer.scrollIntoViewIfNeeded();
        const atlas = page.frames().find(f => f.url().includes('/archeon-atlas/index.html'));
        assert(atlas);
        await atlas.waitForFunction(() => window.ATLAS_APP?.ready);
        assert.deepEqual(await atlas.locator('.view-tabs [data-tab]').evaluateAll(elements => elements.map(el => el.dataset.tab)), ['world', 'aethelgard', 'local', 'system', 'federation', 'character']);
        assert.match(await atlas.locator('[data-tab="character"]').textContent(), /06.*Character/);
        assert.equal(await page.locator('a[href="/Character"]').count(), 0);
        await atlas.locator('[data-tab="character"]').click();
        await atlas.waitForFunction(() => window.ATLAS_APP.currentTab === 'character' && window.ATLAS_APP.ready);
        assert.equal(page.url(), base + '/Archeon');
        assert.equal(page.frames().length, 2, 'Character should render inside the Atlas without another iframe');
        assert.equal(await atlas.locator('#character-stage .character-profile').count(), 3);
        assert.equal(await atlas.locator('.sidebar').isVisible(), false);
        assert.equal(await atlas.locator('.map-tools').isVisible(), false);
        for (const image of await atlas.locator('#character-stage img').all()) { await image.scrollIntoViewIfNeeded(); await image.evaluate(el => el.decode()); }
        await atlas.evaluate(() => document.getElementById('character-stage').scrollTop = 0);
        await outer.screenshot({ path: path.join(output, 'atlas-character-desktop.png') });
        result.checks.push('06 Character follows Federation in the same Atlas tab row and opens three portraits in place');
        await atlas.locator('[data-atlas-language="en"]').click();
        assert.equal(await atlas.locator('[data-characters]').getAttribute('lang'), 'en');
        assert.equal(await atlas.locator('#character-stage .character-prose [data-copy="en"]:visible').count(), 9);
        assert.equal(await atlas.locator('#character-stage .character-prose [data-copy="zh"]:visible').count(), 0);
        await atlas.locator('[data-character-lang="zh"]').click();
        assert.equal(await atlas.evaluate(() => window.ATLAS_I18N.locale), 'zh');
        assert.equal(await atlas.locator('[data-atlas-language="zh"]').getAttribute('aria-pressed'), 'true');
        result.checks.push('Atlas and Character language buttons stay synchronized; prose bypasses automatic translation');
        await atlas.evaluate(() => {
            const stage = document.getElementById('character-stage');
            const target = document.querySelector('#lia .character-prose p:nth-child(2)');
            stage.scrollTop += target.getBoundingClientRect().top - stage.getBoundingClientRect().top - 120;
        });
        const before = await atlas.locator('#lia .character-prose p:nth-child(2)').evaluate(el => el.getBoundingClientRect().top);
        await atlas.locator('[data-character-lang="en"]').click();
        const after = await atlas.locator('#lia .character-prose p:nth-child(2)').evaluate(el => el.getBoundingClientRect().top);
        assert(Math.abs(after - before) < 4, 'Embedded reading position shifted: ' + (after - before));
        result.checks.push('Embedded reading position survives a language switch');
        for (const tab of ['world', 'aethelgard', 'system', 'federation']) {
            await atlas.locator(`[data-tab="${tab}"]`).click();
            await atlas.waitForFunction(id => window.ATLAS_APP?.ready && window.ATLAS_APP.currentTab === id, tab, { timeout: 60000 });
            assert.equal(await atlas.locator('#character-stage').isVisible(), false);
            await atlas.locator('[data-tab="character"]').click();
            await atlas.waitForFunction(() => window.ATLAS_APP.ready && window.ATLAS_APP.currentTab === 'character');
            assert.equal(await atlas.locator('#space-stage canvas').count(), 0);
        }
        await atlas.evaluate(() => window.ATLAS_APP.setView('marneth'));
        await atlas.waitForFunction(() => window.ATLAS_APP.ready && window.ATLAS_APP.currentTab === 'local');
        await atlas.locator('[data-tab="character"]').click();
        await atlas.waitForFunction(() => window.ATLAS_APP.ready && window.ATLAS_APP.currentTab === 'character');
        assert.equal(contentRequests, 1, 'Reopening should reuse the loaded profiles');
        result.checks.push('World, Aethelgard, local maps, system and Federation return correctly; disposed star scenes do not cover Character');
        await atlas.evaluate(async () => { const pending = window.ATLAS_APP.setTab('system'); await window.ATLAS_APP.setTab('character'); await pending; });
        assert.equal(await atlas.evaluate(() => window.ATLAS_APP.currentTab), 'character');
        assert.equal(await atlas.locator('#character-stage').isVisible(), true);
        result.checks.push('Rapid tab switching does not restore a stale star scene');
        await page.setViewportSize({ width: 390, height: 844 });
        await atlas.locator('[data-tab="character"]').scrollIntoViewIfNeeded();
        await atlas.locator('[data-character-lang="zh"]').click();
        await atlas.locator('.character-jumps a[href="#lia"]').click();
        assert.equal(await atlas.locator('#lia').isVisible(), true);
        assert(await atlas.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
        await atlas.evaluate(() => document.getElementById('character-stage').scrollTop = 0);
        await outer.screenshot({ path: path.join(output, 'atlas-character-mobile.png') });
        result.checks.push('390px mobile tab scrolling and in-panel character jumps work without horizontal overflow');
        const retryContext = await browser.newContext();
        const retryPage = await retryContext.newPage();
        let failOnce = true;
        await retryPage.route('**/Character', route => { if (failOnce) { failOnce = false; return route.fulfill({ status: 503, body: 'Unavailable' }); } return route.continue(); });
        await retryPage.goto(base + '/archeon-atlas/index.html#view=character');
        await retryPage.locator('.character-panel-status button').click();
        await retryPage.waitForFunction(() => window.ATLAS_APP.ready && window.ATLAS_APP.currentTab === 'character');
        assert.equal(await retryPage.locator('.character-profile').count(), 3);
        result.checks.push('Direct Character-tab links and retry after a failed content request work');
        await retryContext.close();
        assert.deepEqual(result.errors, []);
        assert.deepEqual(result.failedResources, []);
        result.passed = true;
    } finally {
        fs.writeFileSync(path.join(output, 'result.json'), JSON.stringify(result, null, 2));
        await browser.close();
    }
    console.log(JSON.stringify(result));
})().catch(error => { console.error(error); process.exitCode = 1; });
